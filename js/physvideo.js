  function searchCourse(q) {
    q = (q || '').trim().toLowerCase();
    const c = getCourse();
    if (!q) return c;
    const out = { featured: c.featured, chapters: [] };
    c.chapters.forEach(cp => {
      const hitCh = cp.ch.toLowerCase().includes(q);
      const ls = cp.lessons.filter(l => hitCh || (l.title + l.points.join('')).toLowerCase().includes(q));
      if (ls.length) out.chapters.push({ ch: cp.ch, lessons: ls });
    });
    return out;
  }

